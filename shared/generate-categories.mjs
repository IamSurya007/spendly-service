#!/usr/bin/env node
// Generates the platform copies of the category taxonomy from categories.json.
//
//   node shared/generate-categories.mjs
//
// Outputs (paths relative to the Fiscora workspace root):
//   spendly/lib/features/categories/data/category_taxonomy.g.dart
//   spendly-service/src/categories/taxonomy.generated.ts
//   spendly-web/lib/categories.generated.ts
//   spendly-web/components/categories/categoryIcons.generated.tsx
//
// A missing sibling repo is skipped with a warning.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const workspace = resolve(here, '..', '..');
const src = JSON.parse(readFileSync(join(here, 'categories.json'), 'utf8'));

const HEADER = 'GENERATED by spendly-service/shared/generate-categories.mjs from categories.json. Do not edit by hand.';

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s) => camel(s).replace(/^./, (c) => c.toUpperCase());
const dartStr = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const hexToArgb = (hex) => `0xFF${hex.replace('#', '').toUpperCase()}`;

// Flatten: parents then their children, in order.
const flat = [];
src.categories.forEach((p, i) => {
  flat.push({ id: p.id, name: p.name, icon: p.icon, color: p.color, kind: p.kind, parentId: null, sortOrder: i * 100 });
  (p.children || []).forEach((c, j) => {
    flat.push({
      id: c.id,
      name: c.name,
      icon: c.icon,
      color: c.color || p.color,
      kind: p.kind,
      parentId: p.id,
      sortOrder: i * 100 + j + 1,
    });
  });
});

const ids = new Set(flat.map((c) => c.id));
for (const [name, [parent, sub]] of Object.entries(src.legacy)) {
  if (!ids.has(parent) || (sub && !ids.has(sub))) throw new Error(`legacy "${name}" points at unknown id`);
}
for (const [, target] of src.merchantKeywords) {
  if (!ids.has(target)) throw new Error(`merchant keyword target ${target} unknown`);
}

const iconKeys = [...new Set([...flat.map((c) => c.icon), ...src.iconPalette])].sort();

function write(relPath, content) {
  const abs = join(workspace, relPath);
  const repoRoot = join(workspace, relPath.split('/')[0]);
  if (!existsSync(repoRoot)) {
    console.warn(`skip ${relPath} (repo not found)`);
    return;
  }
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, content);
  console.log(`wrote ${relPath}`);
}

// ---------------------------------------------------------------- Dart
{
  const cats = flat
    .map(
      (c) =>
        `  Category(id: ${dartStr(c.id)}, name: ${dartStr(c.name)}, iconKey: ${dartStr(c.icon)}, ` +
        `color: ${hexToArgb(c.color)}, kind: CategoryKind.${c.kind}, ` +
        `parentId: ${c.parentId ? dartStr(c.parentId) : 'null'}, isSystem: true, sortOrder: ${c.sortOrder}),`,
    )
    .join('\n');
  const legacy = Object.entries(src.legacy)
    .map(([k, [p, s]]) => `  ${dartStr(k.toLowerCase())}: (${dartStr(p)}, ${s ? dartStr(s) : 'null'}),`)
    .join('\n');
  const merchant = src.merchantKeywords
    .map(([pat, id]) => `  (${dartStr(pat)}, ${dartStr(id)}),`)
    .join('\n');
  const icons = iconKeys.map((k) => `  ${dartStr(k)}: PhosphorIconsFill.${camel(k)},`).join('\n');
  const palette = src.iconPalette.map(dartStr).join(', ');
  const colors = src.colorPalette.map(hexToArgb).join(', ');

  write(
    'spendly/lib/features/categories/data/category_taxonomy.g.dart',
    `// ${HEADER}
// ignore_for_file: lines_longer_than_80_chars

import 'package:flutter/widgets.dart';
import 'package:phosphor_flutter/phosphor_flutter.dart';

import '../models/category.dart';

const int categoryTaxonomyVersion = ${src.version};

const String defaultDebitCategoryId = ${dartStr(src.defaults.debit)};
const String defaultCreditCategoryId = ${dartStr(src.defaults.credit)};

/// Parents first, each followed by its subcategories.
const List<Category> systemCategories = [
${cats}
];

/// Lower-cased legacy name -> (parentId, subcategoryId).
const Map<String, (String, String?)> legacyCategoryMap = {
${legacy}
};

/// (pipe-separated whole-word keywords, category id). First match wins.
const List<(String, String)> merchantKeywordRules = [
${merchant}
];

const Map<String, IconData> categoryIcons = {
${icons}
};

/// Icons offered when creating or editing a category.
const List<String> categoryIconPalette = [${palette}];

const List<int> categoryColorPalette = [${colors}];
`,
  );
}

// ---------------------------------------------------------------- TypeScript (shared body)
function tsBody() {
  const cats = flat
    .map(
      (c) =>
        `  { id: ${JSON.stringify(c.id)}, name: ${JSON.stringify(c.name)}, icon: ${JSON.stringify(c.icon)}, ` +
        `color: ${JSON.stringify(c.color)}, kind: ${JSON.stringify(c.kind)}, parentId: ${JSON.stringify(c.parentId)}, sortOrder: ${c.sortOrder} },`,
    )
    .join('\n');
  const legacy = Object.entries(src.legacy)
    .map(([k, [p, s]]) => `  ${JSON.stringify(k.toLowerCase())}: [${JSON.stringify(p)}, ${JSON.stringify(s)}],`)
    .join('\n');
  const merchant = src.merchantKeywords.map(([p, id]) => `  [${JSON.stringify(p)}, ${JSON.stringify(id)}],`).join('\n');
  return `export type CategoryKind = 'expense' | 'income' | 'transfer';

export interface SystemCategory {
  id: string;
  name: string;
  icon: string;
  color: string;
  kind: CategoryKind;
  parentId: string | null;
  sortOrder: number;
}

export const CATEGORY_TAXONOMY_VERSION = ${src.version};
export const DEFAULT_DEBIT_CATEGORY_ID = ${JSON.stringify(src.defaults.debit)};
export const DEFAULT_CREDIT_CATEGORY_ID = ${JSON.stringify(src.defaults.credit)};

/** Parents first, each followed by its subcategories. */
export const SYSTEM_CATEGORIES: SystemCategory[] = [
${cats}
];

/** Lower-cased legacy name -> [parentId, subcategoryId]. */
export const LEGACY_CATEGORY_MAP: Record<string, [string, string | null]> = {
${legacy}
};

/** [pipe-separated whole-word keywords, category id]. First match wins. */
export const MERCHANT_KEYWORD_RULES: [string, string][] = [
${merchant}
];

export const CATEGORY_ICON_PALETTE: string[] = ${JSON.stringify(src.iconPalette)};
export const CATEGORY_COLOR_PALETTE: string[] = ${JSON.stringify(src.colorPalette)};
`;
}

write('spendly-service/src/categories/taxonomy.generated.ts', `// ${HEADER}\n/* eslint-disable */\n\n${tsBody()}`);
write('spendly-web/lib/categories.generated.ts', `// ${HEADER}\n\n${tsBody()}`);

// ---------------------------------------------------------------- Web icons
{
  const imports = iconKeys.map((k) => `  ${pascal(k)},`).join('\n');
  const map = iconKeys.map((k) => `  ${JSON.stringify(k)}: ${pascal(k)},`).join('\n');
  write(
    'spendly-web/components/categories/categoryIcons.generated.tsx',
    `// ${HEADER}
'use client';

import type { Icon } from '@phosphor-icons/react';
import {
${imports}
} from '@phosphor-icons/react';

export const CATEGORY_ICONS: Record<string, Icon> = {
${map}
};
`,
  );
}
